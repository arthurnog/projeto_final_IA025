tokenizer_ptt5 = AutoTokenizer.from_pretrained(nome_modelo_seq2seq)

# 4. Função de pré-processamento Seq2Seq (Tokenizar Inputs e Targets)
def preprocessar_seq2seq(exemplos):
    model_inputs = tokenizer_ptt5(
        exemplos["input_text"],
        max_length=128,
        truncation=True,
        padding="max_length"
    )

    # Tokenizar as respostas esperadas (targets)
    labels = tokenizer_ptt5(
        text_target=exemplos["target_text"],
        max_length=128,
        truncation=True,
        padding="max_length"
    )

    # Substituir os tokens de padding nos labels por -100 para o PyTorch ignorá-los no cálculo do loss
    labels_ids = labels["input_ids"]
    labels_ids = [
        [(label if label != tokenizer_ptt5.pad_token_id else -100) for label in seq]
        for seq in labels_ids
    ]

    model_inputs["labels"] = labels_ids
    return model_inputs

# Tokenizar o dataset inteiro
dataset_seq2seq_tokenizado = dataset_seq2seq_split.map(
    preprocessar_seq2seq,
    batched=True,
    remove_columns=["input_text", "target_text"]
)

