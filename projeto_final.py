import os
import torch
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM, AutoModelForSequenceClassification

# 1. Carregar o melhor checkpoint do PTT5
pasta_ptt5 = "./modelo_simplificador_ptt5"
