def compute_metrics(eval_pred):
    logits, labels = eval_pred
    predicoes = np.argmax(logits, axis=-1)

    acc = metrica_acc.compute(predictions=predicoes, references=labels)["accuracy"]
    f1 = metrica_f1.compute(predictions=predicoes, references=labels)["f1"]

    return {"accuracy": acc, "f1": f1}

