melhor_checkpoint_ptt5 = sorted(checkpoints_ptt5, key=lambda x: int(x.split("-")[-1]))[-1]

print(f"Carregando PTT5 de: {melhor_checkpoint_ptt5}")
tokenizer_ptt5 = AutoTokenizer.from_pretrained("unicamp-dl/ptt5-base-portuguese-vocab")
modelo_ptt5 = AutoModelForSeq2SeqLM.from_pretrained(melhor_checkpoint_ptt5)

# 2. Carregar o melhor checkpoint do BERTimbau
pasta_bert = "./modelo_classificador_porsimples"
checkpoints_bert = [os.path.join(pasta_bert, d) for d in os.listdir(pasta_bert) if d.startswith("checkpoint")]
melhor_checkpoint_bert = sorted(checkpoints_bert, key=lambda x: int(x.split("-")[-1]))[-1]

print(f"Carregando BERTimbau de: {melhor_checkpoint_bert}")
tokenizer_bert = AutoTokenizer.from_pretrained("neuralmind/bert-base-portuguese-cased")
modelo_bert = AutoModelForSequenceClassification.from_pretrained(melhor_checkpoint_bert)

# 3. Função da Pipeline
def simplificar_e_avaliar(texto_original):
    # PTT5 gera o texto simplificado
    input_text = "simplifique: " + texto_original
    inputs = tokenizer_ptt5(input_text, return_tensors="pt", truncation=True, max_length=128)

    outputs = modelo_ptt5.generate(**inputs, max_length=128, num_beams=4, early_stopping=True)
    texto_simplificado = tokenizer_ptt5.decode(outputs[0], skip_special_tokens=True)

    # BERTimbau avalia se o resultado é simplificado (Classe 1) ou complexo (Classe 0)
    inputs_bert = tokenizer_bert(texto_simplificado, return_tensors="pt", truncation=True, max_length=128)
    with torch.no_grad():
        logits = modelo_bert(**inputs_bert).logits
        probs = torch.nn.functional.softmax(logits, dim=-1)

    classe = torch.argmax(probs).item()
    confianca = probs[0][classe].item()
    rotulo = "Simplificada (1)" if classe == 1 else "Original/Complexa (0)"

    print(f"--- TESTE DE PIPELINE ---")
    print(f"Original:     {texto_original}")
    print(f"Simplificada: {texto_simplificado}")
    print(f"Avaliação BERTimbau: {rotulo} ({confianca:.2%})\n")

# Testar o fluxo completo
simplificar_e_avaliar("O magistrado indeferiu o pedido de liminar pleiteado pelo requerente devido à ausência de provas das alegações trazidas.")

